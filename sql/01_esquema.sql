BEGIN;

-- ---------- Catálogos (listas seleccionables; se desactivan, no se borran) ----------
CREATE TABLE IF NOT EXISTS clientes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      text NOT NULL UNIQUE CHECK (btrim(nombre) <> ''),
  activo      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS proveedores (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      text NOT NULL UNIQUE CHECK (btrim(nombre) <> ''),
  activo      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS solicitantes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      text NOT NULL UNIQUE CHECK (btrim(nombre) <> ''),
  activo      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS tipos_servicio (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      text NOT NULL UNIQUE CHECK (btrim(nombre) <> ''),
  activo      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------- Destinatarios de correos automáticos ----------
CREATE TABLE IF NOT EXISTS destinatarios_alerta (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          text NOT NULL,
  email           text NOT NULL UNIQUE CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  activo          boolean NOT NULL DEFAULT true,
  recibe_alerta   boolean NOT NULL DEFAULT true,
  recibe_respaldo boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL DEFAULT now()
);

-- ---------- Roles (por correo de inicio de sesión, en minúsculas) ----------
CREATE TABLE IF NOT EXISTS administradores (
  email       text PRIMARY KEY CHECK (email = lower(btrim(email)) AND email LIKE '%@%'),
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS usuarios_vista (
  email       text PRIMARY KEY CHECK (email = lower(btrim(email)) AND email LIKE '%@%'),
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------- Tabla principal ----------
CREATE TABLE IF NOT EXISTS agregados (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id           bigint NOT NULL REFERENCES clientes(id)       ON DELETE RESTRICT,
  proveedor_id         bigint NOT NULL REFERENCES proveedores(id)    ON DELETE RESTRICT,
  contrarrecibo        text,
  nur                  text   NOT NULL,
  cpt                  text   NOT NULL,
  descripcion          text   NOT NULL,
  tipo_servicio_id     bigint NOT NULL REFERENCES tipos_servicio(id) ON DELETE RESTRICT,
  solicitante_id       bigint NOT NULL REFERENCES solicitantes(id)   ON DELETE RESTRICT,
  fecha_solicitud      date   NOT NULL,
  fecha_carga          date,
  estatus              text   NOT NULL DEFAULT 'PENDIENTE'
                       CHECK (estatus IN ('PENDIENTE','CARGADO','ACLARACIÓN SERVICIO NO BRINDADO')),
  notas                text,
  anio_surtido         smallint NOT NULL
                       DEFAULT EXTRACT(YEAR FROM (now() AT TIME ZONE 'America/Mexico_City'))::smallint
                       CHECK (anio_surtido BETWEEN 2020 AND 2100),
  -- Origen: EXCEL_2026 = migrado de la hoja original (admite blancos); SISTEMA = capturado aquí
  origen               text NOT NULL DEFAULT 'SISTEMA' CHECK (origen IN ('EXCEL_2026','SISTEMA')),
  fila_excel           integer UNIQUE,
  requiere_revision    boolean NOT NULL DEFAULT false,
  motivo_revision      text,
  -- Bajas lógicas (no existe DELETE)
  eliminado            boolean NOT NULL DEFAULT false,
  eliminado_en         timestamptz,
  eliminado_por        text,
  motivo_baja          text,
  -- Seguimiento con proveedor (modo vista)
  solicitado_proveedor boolean NOT NULL DEFAULT false,
  solicitado_en        timestamptz,
  solicitado_por       text,
  created_at           timestamptz NOT NULL DEFAULT now(),
  created_by           text DEFAULT (auth.jwt() ->> 'email'),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  updated_by           text DEFAULT (auth.jwt() ->> 'email'),
  CONSTRAINT chk_fecha_carga_posterior CHECK (fecha_carga IS NULL OR fecha_carga >= fecha_solicitud),
  CONSTRAINT chk_sin_blancos_registros_nuevos CHECK (
    origen = 'EXCEL_2026' OR (btrim(coalesce(contrarrecibo,'')) <> '' AND btrim(nur) <> '' AND btrim(cpt) <> '' AND btrim(descripcion) <> '')
  ),
  CONSTRAINT chk_baja_completa CHECK (eliminado = false OR (eliminado_en IS NOT NULL AND btrim(coalesce(motivo_baja,'')) <> ''))
);
CREATE INDEX IF NOT EXISTS idx_agregados_nur             ON agregados (nur);
CREATE INDEX IF NOT EXISTS idx_agregados_cpt             ON agregados (cpt);
CREATE INDEX IF NOT EXISTS idx_agregados_fecha_solicitud ON agregados (fecha_solicitud);
CREATE INDEX IF NOT EXISTS idx_agregados_estatus         ON agregados (estatus) WHERE eliminado = false;
CREATE INDEX IF NOT EXISTS idx_agregados_proveedor       ON agregados (proveedor_id);

-- ---------- Historial (lo llena un trigger; solo lectura para la página) ----------
CREATE TABLE IF NOT EXISTS agregados_historial (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agregado_id    bigint NOT NULL,
  operacion      text   NOT NULL,
  datos_antes    jsonb,
  datos_despues  jsonb,
  usuario        text DEFAULT (auth.jwt() ->> 'email'),
  fecha          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_historial_agregado ON agregados_historial (agregado_id);

-- ---------- Catálogo de procedimientos (independiente; llena tipo y descripción por CPT) ----------
CREATE TABLE IF NOT EXISTS catalogo_procedimientos (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cpt             text,
  descripcion     text NOT NULL,
  tipo_servicio   text NOT NULL,
  grupo_servicio  text NOT NULL DEFAULT '',
  status          text NOT NULL DEFAULT 'Habilitado' CHECK (status IN ('Habilitado','Deshabilitado'))
);
CREATE INDEX IF NOT EXISTS idx_catalogo_cpt ON catalogo_procedimientos (upper(cpt));

COMMIT;
